//! `mgc-sprite-export`: the world sprites as plain files, for working on
//! the art outside the game (AI re-imaging, meshing, re-rendering into
//! impostor packs).
//!
//! ```text
//! mgc-sprite-export <baked-dir> <out-dir> [--census <tsv>] [variant ...]
//! ```
//!
//! Reads each graphics variant's baked impostor pack (so the bake's
//! asset corrections are already applied) and writes, per variant:
//!
//! - `<family>/` — one folder per visual family (`f<base>-t<draw>`):
//!   every distinct picture as RGBA PNG (`v<k>` views, `p<k>` animation
//!   poses, `s00` single; FLC streams as `-f<nn>` frames), a
//!   `.glow.png` mask beside any picture with self-lit texels, `hero.png`
//!   (the one picture to start from), `turntable.png` (view families:
//!   the views side by side in angle order, feet aligned) and
//!   `family.json` (status, sector table, mirrors, anchors, world
//!   heights, recolour links — what a re-import needs).
//! - `heroes/<family>.png` — the WORK LIST: the hero of every family
//!   that is used, not replaced by an enhanced effect, and not a
//!   recolour of another family. `contact.png` shows them labelled,
//!   `contact-all.png` every family, `worklist.txt` the ids.
//! - `index.json` — every family with its status.
//!
//! `--census` is the `MGC_SPRITE_CENSUS` output of a replay-check sweep
//! (`replay::replay_check`): which sprite-table rows real play put on
//! screen, and as what. Without it every family's use is `unknown`.
//!
//! `README.md` at the output root states the conventions.

