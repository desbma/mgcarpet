//! `mgc-sprite-export`: the world sprites as plain files, for working on
//! the art outside the game (AI re-imaging, meshing, re-rendering into
//! impostor packs).
//!
//! ```text
//! mgc-sprite-export <baked-dir> <out-dir> [variant ...]
//! ```
//!
//! Reads each graphics variant's baked impostor pack (so the bake's
//! asset corrections are already applied) and writes, per variant:
//!
//! - `<family>/` — one folder per visual family (`f<base>-t<draw>`):
//!   every distinct picture as RGBA PNG (`v<k>` views, `p<k>` animation
//!   poses, `s00` single; FLC streams as `-f<nn>` frames), a
//!   `.glow.png` mask beside any picture with self-lit texels, `hero.png`
//!   (the one picture to start from), `turntable.png` (view families:
//!   the views side by side in angle order, feet aligned) and
//!   `family.json` (sector table, mirrors, anchors, world heights — what
//!   a re-import needs).
//! - `heroes/<family>.png` — every family's hero, flat, for batch use.
//! - `contact.png` — the heroes on a labelled grid (label = the family
//!   id without the `f`/`t`: `<base>-<draw>`), `index.json`.
//!
//! `README.md` at the output root states the conventions.

use std::path::{Path, PathBuf};

use mgc_formats::Game;
use mgc_formats::bundle::Bundle;
use mgc_formats::impostor::{ImpostorPack, ModelKey, Playback, retail};
use mgc_sim::ids::GameId;
use serde_json::json;

/// Variants exported when none are named.
const VARIANTS: [&str; 6] = [
    "mc1-temperate",
    "mc1-arctic",
    "mc2-day",
    "mc2-night",
    "mc2-night-fog",
    "mc2-cave",
];

/// The hero view: the front three-quarter — face and flank both in
/// frame (player, 2026-10-06: "a roughly 45 degree from the side
/// shot"). Measured like `view_angle_deg` (0 = from behind, 180 = head
/// on).
const HERO_ANGLE: f32 = 135.0;

const README: &str = "\
# Exported world sprites

Generated by `mgc-sprite-export` from the baked impostor packs
(docs/FORMAT.md \"Impostor packs\"). Pictures are the original pixels,
1:1, resolved through the variant's palette; alpha 0 = transparent.

## Families

A family (`f<base>-t<draw>`) is one thing an entity can look like:
the sprite id of its first picture and retail's draw type.

- `views` (draw types 17-20): the creature seen from around it.
  `view_angle_deg` is where the CAMERA stands, measured around the
  creature from directly BEHIND it: 0 = its back, 90 = its RIGHT flank
  (head pointing to screen right), 180 = head on. Retail stores only
  0..180 and shows the other half MIRRORED (the `sectors` table in
  `family.json`; 270 = the 90 picture flipped). The angles are the
  ones the pictures were evidently drawn at (view 4 of an 8-view
  family is an exact side profile).
- `animation` (draw types 2-16, 22-36): one picture per animation
  pose `p<k>`, chosen by the game; no views.
- `single`: one picture, the same from every side.

A picture flagged `flc_loop` is an animated stream: `-f00` is the base
image, `-f01..` the loop the game plays (it never returns to f00).

## Placement

`anchor_px` = where the entity's position (its feet) is in the
picture, pixels from the top-left. `rows[].world_height_tiles` = how
tall the game draws the WHOLE picture (1 tile = 256 world units; a
family drawn by several sprite-table rows lists each). Width follows
from the picture's pixel aspect.

## Glow

`*.glow.png`: white = texels the renderer treats as self-lit in this
variant (they resist darkness, not fog). Only written where a picture
has any.

## Hero

`hero.png` (and `heroes/`) is the view nearest the front three-quarter
(135 degrees) — face and flank both visible; pose 0 / the base image
for animated and single families.
";

/// Camera bearing a retail picture was drawn at (see README).
fn view_angle_deg(draw_type: u8, offset: u16) -> f32 {
    match draw_type {
        17 | 18 => offset as f32 * 22.5,
        19 => offset as f32 * 45.0,
        20 => offset as f32 * 90.0,
        _ => 0.0,
    }
}

fn game_id(g: Game) -> GameId {
    match g {
        Game::MagicCarpet1 => GameId::Mc1,
        Game::HiddenWorlds => GameId::Mc1Hw,
        Game::MagicCarpet2 => GameId::Mc2,
    }
}

/// One exported picture (one impostor clip).
struct Picture {
    name: String,
    angle: Option<f32>,
    w: u32,
    h: u32,
    anchor_px: [f32; 2],
    files: Vec<String>,
    glow: Vec<Option<String>>,
    playback: Playback,
    /// RGBA of the first frame (hero / turntable / contact sheet).
    rgba0: Vec<u8>,
}

struct Ctx<'a> {
    pack: &'a ImpostorPack,
    palette: [[u8; 4]; 256],
    glow: [bool; 256],
}

impl Ctx<'_> {
    /// RGBA + glow mask (None when nothing glows) of pack image `i`.
    fn image(&self, i: usize) -> (u32, u32, Vec<u8>, Option<Vec<u8>>) {
        let im = &self.pack.index.images[i];
        let aw = self.pack.index.atlas_width as usize;
        let mut rgba = Vec::with_capacity((im.w * im.h * 4) as usize);
        let mut mask = Vec::with_capacity((im.w * im.h * 4) as usize);
        let mut any = false;
        for r in 0..im.h as usize {
            for c in 0..im.w as usize {
                let q = self.pack.pixels[(im.y as usize + r) * aw + im.x as usize + c];
                if q == 0 {
                    rgba.extend_from_slice(&[0, 0, 0, 0]);
                    mask.extend_from_slice(&[0, 0, 0, 0]);
                } else {
                    let p = self.palette[q as usize];
                    rgba.extend_from_slice(&[p[0], p[1], p[2], 255]);
                    let g = self.glow[q as usize];
                    any |= g;
                    mask.extend_from_slice(if g {
                        &[255, 255, 255, 255]
                    } else {
                        &[0, 0, 0, 0]
                    });
                }
            }
        }
        (im.w, im.h, rgba, any.then_some(mask))
    }

    /// Write clip `clip` as picture `name` into `dir`.
    fn picture(
        &self,
        dir: &Path,
        name: String,
        angle: Option<f32>,
        clip: u32,
    ) -> Result<Picture, String> {
        let c = self.pack.index.clips[clip as usize];
        let n = match c.playback {
            Playback::Still => 1,
            Playback::FlcLoop => c.len,
        };
        let im = self.pack.index.images[c.first as usize];
        let mut files = Vec::new();
        let mut glow = Vec::new();
        let mut rgba0 = Vec::new();
        for k in 0..n {
            let (w, h, rgba, mask) = self.image((c.first + k) as usize);
            let stem = if n == 1 {
                name.clone()
            } else {
                format!("{name}-f{k:02}")
            };
            crate::write_png(&dir.join(format!("{stem}.png")), w, h, &rgba)?;
            files.push(format!("{stem}.png"));
            glow.push(match mask {
                Some(m) => {
                    crate::write_png(&dir.join(format!("{stem}.glow.png")), w, h, &m)?;
                    Some(format!("{stem}.glow.png"))
                }
                None => None,
            });
            if k == 0 {
                rgba0 = rgba;
            }
        }
        Ok(Picture {
            name,
            angle,
            w: im.w,
            h: im.h,
            anchor_px: [
                im.anchor[0] * im.w as f32,
                (1.0 - im.anchor[1]) * im.h as f32,
            ],
            files,
            glow,
            playback: c.playback,
            rgba0,
        })
    }
}

/// Bottom-aligned horizontal strip of pictures, `gap` transparent px
/// apart.
fn strip(pics: &[&Picture], gap: u32) -> (u32, u32, Vec<u8>) {
    let h = pics.iter().map(|p| p.h).max().unwrap_or(1);
    let w = pics.iter().map(|p| p.w).sum::<u32>() + gap * pics.len().saturating_sub(1) as u32;
    let mut out = vec![0u8; (w * h * 4) as usize];
    let mut x0 = 0;
    for p in pics {
        let y0 = h - p.h;
        for r in 0..p.h {
            let s = (r * p.w * 4) as usize;
            let d = (((y0 + r) * w + x0) * 4) as usize;
            out[d..d + (p.w * 4) as usize].copy_from_slice(&p.rgba0[s..s + (p.w * 4) as usize]);
        }
        x0 += p.w + gap;
    }
    (w.max(1), h, out)
}

/// 3x5 glyphs for contact-sheet labels: digits and '-'.
fn glyph(c: char) -> [u8; 5] {
    match c {
        '0' => [7, 5, 5, 5, 7],
        '1' => [2, 6, 2, 2, 7],
        '2' => [7, 1, 7, 4, 7],
        '3' => [7, 1, 7, 1, 7],
        '4' => [5, 5, 7, 1, 1],
        '5' => [7, 4, 7, 1, 7],
        '6' => [7, 4, 7, 5, 7],
        '7' => [7, 1, 1, 1, 1],
        '8' => [7, 5, 7, 5, 7],
        '9' => [7, 5, 7, 1, 7],
        '-' => [0, 0, 7, 0, 0],
        _ => [0; 5],
    }
}

/// The heroes on a labelled grid.
fn contact_sheet(path: &Path, items: &[(String, &Picture)]) -> Result<(), String> {
    const CELL: u32 = 132;
    const LABEL: u32 = 14;
    const PER: u32 = 10;
    let rows = (items.len() as u32).div_ceil(PER).max(1);
    let (w, h) = (PER * CELL, rows * (CELL + LABEL));
    let mut out = Vec::with_capacity((w * h * 4) as usize);
    for _ in 0..w * h {
        out.extend_from_slice(&[150, 165, 185, 255]);
    }
    let mut put = |x: u32, y: u32, c: [u8; 4]| {
        if x < w && y < h {
            let i = ((y * w + x) * 4) as usize;
            out[i..i + 4].copy_from_slice(&c);
        }
    };
    for (n, (label, p)) in items.iter().enumerate() {
        let (cx, cy) = ((n as u32 % PER) * CELL, (n as u32 / PER) * (CELL + LABEL));
        for (i, ch) in label.chars().enumerate() {
            let g = glyph(ch);
            for (gy, bits) in g.iter().enumerate() {
                for gx in 0..3u32 {
                    if bits & (4 >> gx) != 0 {
                        for (sx, sy) in [(0, 0), (1, 0), (0, 1), (1, 1)] {
                            put(
                                cx + 4 + i as u32 * 8 + gx * 2 + sx,
                                cy + CELL + 1 + gy as u32 * 2 + sy,
                                [20, 20, 24, 255],
                            );
                        }
                    }
                }
            }
        }
        // Integer downscale to fit the cell, feet on the cell floor,
        // the label right under it.
        let f = p.w.max(p.h).div_ceil(CELL - 4).max(1);
        let (tw, th) = (p.w / f, p.h / f);
        let ox = cx + (CELL - tw) / 2;
        let oy = cy + CELL - 2 - th;
        for y in 0..th {
            for x in 0..tw {
                let i = (((y * f) * p.w + x * f) * 4) as usize;
                if p.rgba0[i + 3] != 0 {
                    put(
                        ox + x,
                        oy + y,
                        [p.rgba0[i], p.rgba0[i + 1], p.rgba0[i + 2], 255],
                    );
                }
            }
        }
    }
    crate::write_png(path, w, h, &out)
}

fn export_variant(baked: &Path, out: &Path, variant: &str) -> Result<usize, String> {
    let bundle = Bundle::load(&baked.join("assets").join(variant)).map_err(|e| e.to_string())?;
    let pack = bundle
        .impostors
        .as_ref()
        .ok_or_else(|| format!("{variant}: no impostor pack (re-bake)"))?;
    let (index, _) = bundle
        .sprites
        .as_ref()
        .ok_or_else(|| format!("{variant}: no sprite bank"))?;
    let game = game_id(bundle.manifest.game);
    let mut pal3 = [[0u8; 3]; 256];
    for (d, s) in pal3.iter_mut().zip(bundle.palette.iter()) {
        *d = [s[0], s[1], s[2]];
    }
    let ctx = Ctx {
        pack,
        palette: bundle.palette,
        glow: mgc_render::grade::build(&pal3, &bundle.shade_lut).glow,
    };
    // Which sprite-table rows draw each family, and how tall.
    let dims = |id: u16| {
        index
            .sprites
            .get(id as usize)
            .map(|s| (s.width, s.height, s.flags))
    };
    let nrows = match game {
        GameId::Mc1 | GameId::Mc1Hw => mgc_sim::mc1::sprite_stats::SPRITE_STATS.len(),
        GameId::Mc2 => mgc_sim::mc2::sprite_params::SPRITE_PARAMS.len(),
    };
    let mut rows_of = std::collections::BTreeMap::<ModelKey, Vec<serde_json::Value>>::new();
    for row in 0..nrows as u16 {
        if let Some(s) = crate::entities::resolve_pose_sprite(game, row, &dims) {
            let key = ModelKey {
                sprite_base: s.sprite_base,
                draw_type: s.draw_type,
            };
            rows_of
                .entry(key)
                .or_default()
                .push(json!({"row": row, "world_height_tiles": s.world_h}));
        }
    }

    let vdir = out.join(variant);
    let heroes = vdir.join("heroes");
    std::fs::create_dir_all(&heroes).map_err(|e| e.to_string())?;
    let mut families = Vec::new();
    let mut sheet: Vec<(String, Picture)> = Vec::new();
    for model in &pack.index.models {
        let key = model.key;
        let dt = key.draw_type;
        let id = format!("f{:04}-t{dt:02}", key.sprite_base);
        let dir = vdir.join(&id);
        let cell = |pose: usize, sector: usize| {
            model.cells[pose * model.pitches.len() * model.yaw_sectors as usize + sector]
        };
        let kind = if retail::is_view_type(dt) {
            "views"
        } else if retail::pose_count(dt) > 1 {
            "animation"
        } else {
            "single"
        };
        // (picture name, angle, clip) in first-use order.
        let mut wanted: Vec<(String, Option<f32>, u32)> = Vec::new();
        let mut sectors = Vec::new();
        let mut poses = Vec::new();
        match kind {
            "views" => {
                for s in 0..16u16 {
                    let (off, mirror) = retail::member(dt, s, 0);
                    let name = format!("v{off:02}");
                    let c = cell(0, s as usize);
                    if let Some(clip) = c.clip
                        && !wanted.iter().any(|w| w.0 == name)
                    {
                        wanted.push((name.clone(), Some(view_angle_deg(dt, off)), clip));
                    }
                    sectors.push(json!({
                        "sector": s,
                        "camera_from_deg": s as f32 * 22.5,
                        "camera_to_deg": (s + 1) as f32 * 22.5,
                        "picture": c.clip.map(|_| name),
                        "mirror": mirror,
                    }));
                }
            }
            "animation" => {
                for p in 0..model.poses as usize {
                    let name = format!("p{p:02}");
                    let c = cell(p, 0);
                    if let Some(clip) = c.clip {
                        wanted.push((name.clone(), None, clip));
                    }
                    poses.push(json!({"pose": p, "picture": c.clip.map(|_| name)}));
                }
            }
            _ => {
                if let Some(clip) = cell(0, 0).clip {
                    wanted.push(("s00".into(), None, clip));
                }
            }
        }
        if wanted.is_empty() {
            continue; // every member missing/corrupt in this bank
        }
        std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
        let mut pics = Vec::new();
        for (name, angle, clip) in wanted {
            pics.push(ctx.picture(&dir, name, angle, clip)?);
        }
        // Hero: nearest the front three-quarter; ties toward the side.
        let hero = pics
            .iter()
            .min_by(|a, b| {
                let k = |p: &Picture| {
                    let a = p.angle.unwrap_or(HERO_ANGLE);
                    ((a - HERO_ANGLE).abs(), (a - 90.0).abs())
                };
                k(a).partial_cmp(&k(b)).expect("finite")
            })
            .expect("non-empty");
        let hero_name = hero.name.clone();
        let hero_file = hero.files[0].clone();
        std::fs::copy(dir.join(&hero_file), dir.join("hero.png")).map_err(|e| e.to_string())?;
        std::fs::copy(dir.join(&hero_file), heroes.join(format!("{id}.png")))
            .map_err(|e| e.to_string())?;
        if let Some(g) = &hero.glow[0] {
            std::fs::copy(dir.join(g), dir.join("hero.glow.png")).map_err(|e| e.to_string())?;
            std::fs::copy(dir.join(g), heroes.join(format!("{id}.glow.png")))
                .map_err(|e| e.to_string())?;
        }
        if kind == "views" {
            let mut order: Vec<&Picture> = pics.iter().collect();
            order.sort_by(|a, b| a.angle.partial_cmp(&b.angle).expect("finite"));
            let (w, h, rgba) = strip(&order, 4);
            crate::write_png(&dir.join("turntable.png"), w, h, &rgba)?;
        }
        let rows = rows_of.get(&key).cloned().unwrap_or_default();
        let pictures: Vec<serde_json::Value> = pics
            .iter()
            .map(|p| {
                json!({
                    "name": p.name,
                    "view_angle_deg": p.angle,
                    "width": p.w,
                    "height": p.h,
                    "anchor_px": p.anchor_px,
                    "playback": match p.playback { Playback::Still => "still", Playback::FlcLoop => "flc_loop" },
                    "frames": p.files,
                    "glow": p.glow,
                })
            })
            .collect();
        let family = json!({
            "id": id,
            "variant": variant,
            "key": {"sprite_base": key.sprite_base, "draw_type": dt},
            "kind": kind,
            "rows": rows,
            "hero": hero_name,
            "pictures": pictures,
            "sectors": sectors,
            "poses": poses,
        });
        std::fs::write(
            dir.join("family.json"),
            serde_json::to_vec_pretty(&family).expect("serializes"),
        )
        .map_err(|e| e.to_string())?;
        families.push(json!({"id": id, "kind": kind, "key": family["key"], "rows": family["rows"], "hero": hero_name}));
        let hero_idx = pics.iter().position(|p| p.name == hero_name).expect("hero");
        let hero_pic = pics.swap_remove(hero_idx);
        sheet.push((format!("{}-{dt}", key.sprite_base), hero_pic));
    }
    let refs: Vec<(String, &Picture)> = sheet.iter().map(|(l, p)| (l.clone(), p)).collect();
    contact_sheet(&vdir.join("contact.png"), &refs)?;
    std::fs::write(
        vdir.join("index.json"),
        serde_json::to_vec_pretty(&json!({"variant": variant, "families": families}))
            .expect("serializes"),
    )
    .map_err(|e| e.to_string())?;
    Ok(families.len())
}

/// The `mgc-sprite-export` entry point.
pub fn main() -> std::process::ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if args.len() < 2 {
        eprintln!("usage: mgc-sprite-export <baked-dir> <out-dir> [variant ...]");
        return std::process::ExitCode::FAILURE;
    }
    let (baked, out) = (PathBuf::from(&args[0]), PathBuf::from(&args[1]));
    let variants: Vec<&str> = if args.len() > 2 {
        args[2..].iter().map(String::as_str).collect()
    } else {
        VARIANTS.to_vec()
    };
    if let Err(e) =
        std::fs::create_dir_all(&out).and_then(|()| std::fs::write(out.join("README.md"), README))
    {
        eprintln!("{}: {e}", out.display());
        return std::process::ExitCode::FAILURE;
    }
    let mut ok = true;
    for v in variants {
        match export_variant(&baked, &out, v) {
            Ok(n) => println!("{v}: {n} families -> {}", out.join(v).display()),
            Err(e) => {
                eprintln!("{v}: {e}");
                ok = false;
            }
        }
    }
    if ok {
        std::process::ExitCode::SUCCESS
    } else {
        std::process::ExitCode::FAILURE
    }
}
